def get_project_summary(project_id: int, db_path: Optional[str] = None) -> Dict[str, Any]:
    """Compile comprehensive project overview."""
    project = get_project(project_id, db_path=db_path)
    if not project:
        return {"error": f"Project {project_id} not found"}

    milestones = get_milestones(project_id, db_path=db_path)
    tasks = get_tasks(project_id, db_path=db_path)
    progress = calculate_progress(project_id, db_path=db_path)
    overdue = detect_overdue_tasks(project_id, db_path=db_path)
    next_task = recommend_next_task(project_id, db_path=db_path)
    reviews = get_review_logs(project_id, db_path=db_path)

    return {
        "project": project,
        "milestones": milestones,
        "tasks": tasks,
        "progress": progress,
        "overdue_tasks": overdue,
        "next_task_recommendation": next_task,
        "review_logs": reviews,
    }


def export_csv_report(
    project_id: int,
    output_path: Optional[str] = None,
    db_path: Optional[str] = None,
) -> str:
    """Export project tasks and details to CSV using Pandas."""
    summary = get_project_summary(project_id, db_path=db_path)
    if "error" in summary:
        raise ValueError(summary["error"])

    tasks = summary["tasks"]
    today = date.today()

    rows = []
    for t in tasks:
        is_overdue = False
        if t.get("status") != "Completed" and t.get("due_date"):
            try:
                t_due = datetime.strptime(t["due_date"].strip(), "%Y-%m-%d").date()
                if t_due < today:
                    is_overdue = True
            except Exception:
                pass

        rows.append({
            "Task ID": t["id"],
            "Title": t["title"],
            "Milestone": t.get("milestone_title", "Unassigned"),
            "Priority": t.get("priority", "Medium"),
            "Due Date": t.get("due_date", ""),
            "Status": t.get("status", "Pending"),
            "Overdue": "YES" if is_overdue else "NO",
            "Dependencies": ", ".join(map(str, t.get("dependencies", []))),
            "Description": t.get("description", ""),
        })

    df = pd.DataFrame(rows)
    if output_path is None:
        reports_dir = BASE_DIR / "reports"
        reports_dir.mkdir(parents=True, exist_ok=True)
        output_path = str(reports_dir / f"project_{project_id}_report.csv")

    df.to_csv(output_path, index=False, encoding="utf-8")
    return output_path


def export_txt_report(
    project_id: int,
    output_path: Optional[str] = None,
    db_path: Optional[str] = None,
) -> str:
    """Generate executive project status report in text format."""
    summary = get_project_summary(project_id, db_path=db_path)
    if "error" in summary:
        raise ValueError(summary["error"])

    proj = summary["project"]
    prog = summary["progress"]
    overdue = summary["overdue_tasks"]
    next_task = summary["next_task_recommendation"]
    milestones = summary["milestones"]
    tasks = summary["tasks"]

    lines = [
        "=" * 70,
        f" FINAL-YEAR PROJECT STATUS REPORT: {proj['title'].upper()}",
        "=" * 70,
        f"Generated At: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        f"Timeline:     {proj['start_date']} to {proj['deadline']}",
        f"Description:  {proj.get('description', 'N/A')}",
        "-" * 70,
        "PROGRESS SUMMARY:",
        f"• Overall Progress:     {prog['progress_percentage']}%",
        f"• Total Tasks:          {prog['total_tasks']}",
        f"• Completed:            {prog['completed_tasks']}",
        f"• In Progress:          {prog['in_progress_tasks']}",
        f"• Pending:              {prog['pending_tasks']}",
        f"• Blocked:              {prog['blocked_tasks']}",
        f"• Calculation Method:   {prog['method']}",
        "-" * 70,
    ]

    lines.append("OVERDUE TASKS ALERT:")
    if overdue:
        for o in overdue:
            lines.append(f"  [!] Task #{o['id']}: {o['title']} | Due: {o['due_date']} ({o['days_overdue']} days overdue) | Priority: {o['priority']}")
    else:
        lines.append("  None. All incomplete tasks are within schedule.")
    lines.append("-" * 70)

    lines.append("NEXT TASK RECOMMENDATION:")
    if next_task and next_task.get("task"):
        rec = next_task["task"]
        lines.append(f"  --> Recommend: Task #{rec['id']} - {rec['title']}")
        lines.append(f"      Priority: {rec.get('priority')} | Due: {rec.get('due_date')} | Status: {rec.get('status')}")
        lines.append(f"      Reason: {next_task.get('reason')}")
    else:
        reason = next_task.get("reason") if next_task else "No pending eligible tasks."
        lines.append(f"  --> {reason}")
    lines.append("-" * 70)

    lines.append("MILESTONES:")
    for m in milestones:
        lines.append(f"  • Milestone #{m['id']}: {m['title']} (Due: {m.get('due_date')}, Status: {m.get('status')})")
    lines.append("-" * 70)

    lines.append("TASKS BREAKDOWN:")
    for t in tasks:
        deps = f" [Depends on: {t['dependencies']}]" if t.get("dependencies") else ""
        lines.append(f"  [{t['status']}] #{t['id']} {t['title']} (Priority: {t.get('priority')}, Due: {t.get('due_date')}){deps}")
    lines.append("=" * 70)

    report_text = "\n".join(lines)
    if output_path is None:
        reports_dir = BASE_DIR / "reports"
        reports_dir.mkdir(parents=True, exist_ok=True)
        output_path = str(reports_dir / f"project_{project_id}_report.txt")

    Path(output_path).write_text(report_text, encoding="utf-8")
    return output_path


