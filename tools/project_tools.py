def review_results(
    project_id: int,
    action_type: str,
    result_data: Dict[str, Any],
    db_path: Optional[str] = None,
) -> Dict[str, Any]:
    """Deterministic Quality Assurance logic used to review plan or execution results.

    Verifies:
    - Missing fields
    - Dates within bounds
    - Progress calculations against SQLite records
    - Returns decision (Approved/Rejected), target agent (Planner/Worker/None), and feedback.
    """
    proj = get_project(project_id, db_path=db_path)
    if not proj:
        return {
            "decision": "Rejected",
            "target_agent": "Worker",
            "feedback": f"Project ID {project_id} does not exist in SQLite.",
            "verified": False,
        }

    if action_type == "plan_validation":
        plan = result_data.get("plan", {})
        val = validate_plan(plan, proj["start_date"], proj["deadline"])
        if not val["valid"]:
            return {
                "decision": "Rejected",
                "target_agent": "Planner",
                "feedback": "Plan validation failed: " + "; ".join(val["errors"]),
                "verified": False,
            }
        return {
            "decision": "Approved",
            "target_agent": "None",
            "feedback": "Plan structure, milestones, tasks, dates, and dependencies are verified.",
            "verified": True,
        }

    if action_type == "execution_validation":
        # Verify database state
        tasks = get_tasks(project_id, db_path=db_path)
        milestones = get_milestones(project_id, db_path=db_path)

        if len(tasks) == 0:
            return {
                "decision": "Rejected",
                "target_agent": "Worker",
                "feedback": "No tasks were found in database after execution.",
                "verified": False,
            }

        if len(milestones) == 0:
            return {
                "decision": "Rejected",
                "target_agent": "Worker",
                "feedback": "No milestones were found in database after execution.",
                "verified": False,
            }

        # Check claimed progress vs recalculated progress
        claimed_progress = result_data.get("claimed_progress")
        actual_progress = calculate_progress(project_id, db_path=db_path)["progress_percentage"]

        if claimed_progress is not None:
            if abs(float(claimed_progress) - float(actual_progress)) > 0.1:
                return {
                    "decision": "Rejected",
                    "target_agent": "Worker",
                    "feedback": (
                        f"Progress mismatch: claimed {claimed_progress}% but actual SQLite calculation is "
                        f"{actual_progress}%."
                    ),
                    "verified": False,
                }

        return {
            "decision": "Approved",
            "target_agent": "None",
            "feedback": f"Execution verified: {len(milestones)} milestones and {len(tasks)} tasks saved, progress {actual_progress}%.",
            "verified": True,
        }

    return {
        "decision": "Approved",
        "target_agent": "None",
        "feedback": f"Action '{action_type}' checked without issues.",
        "verified": True,
    }


