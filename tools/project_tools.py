def validate_plan(
    plan: Union[Dict[str, Any], str],
    project_start_date: str,
    project_deadline: str,
) -> Dict[str, Any]:
    """Validate structured project plan generated by Planner Agent.

    Checks:
    - Proper JSON structure
    - Milestones non-empty with titles and valid due dates within project bounds
    - Tasks non-empty with title, priority, due date within bounds
    - Task dependencies validity (no self-loops, existing references)
    """
    errors: List[str] = []
    warnings: List[str] = []

    # Parse JSON if passed as string
    data = plan
    if isinstance(plan, str):
        try:
            # Strip markdown fences if present
            cleaned_str = plan.strip()
            if cleaned_str.startswith("```"):
                cleaned_str = re.sub(r"^```(?:json)?\s*", "", cleaned_str)
                cleaned_str = re.sub(r"\s*```$", "", cleaned_str)
            data = json.loads(cleaned_str)
        except Exception as ex:
            return {
                "valid": False,
                "errors": [f"Failed to parse plan as JSON: {str(ex)}"],
                "warnings": [],
                "cleaned_plan": None,
            }

    if not isinstance(data, dict):
        return {
            "valid": False,
            "errors": ["Plan must be a JSON object containing 'milestones' and 'tasks'."],
            "warnings": [],
            "cleaned_plan": None,
        }

    # Parse project dates
    try:
        p_start = datetime.strptime(project_start_date.strip(), "%Y-%m-%d").date()
    except Exception:
        p_start = date.min
    try:
        p_end = datetime.strptime(project_deadline.strip(), "%Y-%m-%d").date()
    except Exception:
        p_end = date.max

    milestones = data.get("milestones", [])
    if not isinstance(milestones, list) or len(milestones) == 0:
        errors.append("Plan must contain at least one milestone.")

    milestone_titles = set()
    cleaned_milestones = []
    for idx, m in enumerate(milestones or []):
        if not isinstance(m, dict):
            errors.append(f"Milestone #{idx + 1} is not a valid object.")
            continue
        m_title = (m.get("title") or "").strip()
        if not m_title:
            errors.append(f"Milestone #{idx + 1} has an empty title.")
        milestone_titles.add(m_title.lower())

        m_due = m.get("due_date")
        if m_due:
            try:
                m_due_date = datetime.strptime(str(m_due).strip(), "%Y-%m-%d").date()
                if m_due_date < p_start or m_due_date > p_end:
                    warnings.append(
                        f"Milestone '{m_title}' due date {m_due} is outside project bounds ({p_start} to {p_end})."
                    )
            except ValueError:
                errors.append(f"Milestone '{m_title}' has invalid due date format '{m_due}'. Expected YYYY-MM-DD.")

        cleaned_milestones.append({
            "title": m_title,
            "description": (m.get("description") or "").strip(),
            "due_date": str(m_due).strip() if m_due else project_deadline,
            "status": m.get("status", "Pending"),
        })

    tasks = data.get("tasks", [])
    if not isinstance(tasks, list) or len(tasks) == 0:
        errors.append("Plan must contain at least one task.")

    valid_priorities = {"Low", "Medium", "High", "Critical"}
    task_identifiers = set()
    cleaned_tasks = []

    for idx, t in enumerate(tasks or []):
        if not isinstance(t, dict):
            errors.append(f"Task #{idx + 1} is not a valid object.")
            continue
        t_title = (t.get("title") or "").strip()
        if not t_title:
            errors.append(f"Task #{idx + 1} has an empty title.")
        task_id_ref = str(t.get("id") or t.get("temp_id") or t_title).strip().lower()
        task_identifiers.add(task_id_ref)
        task_identifiers.add(t_title.lower())

        prio = (t.get("priority") or "Medium").capitalize()
        if prio not in valid_priorities:
            warnings.append(f"Task '{t_title}' has unrecognized priority '{prio}'; defaulting to Medium.")
            prio = "Medium"

        t_due = t.get("due_date")
        if not t_due:
            errors.append(f"Task '{t_title}' is missing a due date.")
        else:
            try:
                t_due_date = datetime.strptime(str(t_due).strip(), "%Y-%m-%d").date()
                if t_due_date < p_start or t_due_date > p_end:
                    errors.append(
                        f"Task '{t_title}' due date ({t_due}) falls outside project timeline ({p_start} to {p_end})."
                    )
            except ValueError:
                errors.append(f"Task '{t_title}' has invalid due date format '{t_due}'. Expected YYYY-MM-DD.")

        deps = t.get("dependencies", []) or t.get("depends_on", [])
        if not isinstance(deps, list):
            deps = [deps] if deps else []

        cleaned_tasks.append({
            "temp_id": t.get("id") or t.get("temp_id") or (idx + 1),
            "milestone_title": (t.get("milestone_title") or t.get("milestone") or "").strip(),
            "title": t_title,
            "description": (t.get("description") or "").strip(),
            "priority": prio,
            "due_date": str(t_due).strip() if t_due else project_deadline,
            "status": t.get("status", "Pending"),
            "dependencies": deps,
        })

    # Validate dependencies exist
    for t in cleaned_tasks:
        t_id_str = str(t["temp_id"]).lower()
        t_title_str = t["title"].lower()
        for dep in t["dependencies"]:
            dep_str = str(dep).strip().lower()
            if dep_str in (t_id_str, t_title_str):
                errors.append(f"Task '{t['title']}' has a self-dependency loop on itself.")

    cleaned_plan = {
        "milestones": cleaned_milestones,
        "tasks": cleaned_tasks,
    }

    return {
        "valid": len(errors) == 0,
        "errors": errors,
        "warnings": warnings,
        "cleaned_plan": cleaned_plan if len(errors) == 0 else None,
    }


