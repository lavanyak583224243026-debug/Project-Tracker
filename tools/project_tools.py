def get_crewai_worker_tools():
    """Wrap core Python functions into CrewAI tools for Worker agent."""
    from crewai.tools import tool

    @tool("Calculate Project Progress")
    def calculate_progress_tool(project_id: int) -> str:
        """Calculate completion percentage and status breakdown for a project in SQLite."""
        return json.dumps(calculate_progress(project_id))

    @tool("Detect Overdue Tasks")
    def detect_overdue_tasks_tool(project_id: int) -> str:
        """Detect tasks past their deadline whose status is not Completed."""
        return json.dumps(detect_overdue_tasks(project_id))

    @tool("Recommend Next Task")
    def recommend_next_task_tool(project_id: int) -> str:
        """Recommend the highest-priority eligible task whose dependencies are satisfied."""
        return json.dumps(recommend_next_task(project_id))

    @tool("Update Task Status")
    def update_task_status_tool_fn(task_id: int, status: str) -> str:
        """Update a task's status in SQLite (Pending, In Progress, Completed, Blocked)."""
        return json.dumps(update_task_status_tool(task_id, status))

    return [
        calculate_progress_tool,
        detect_overdue_tasks_tool,
        recommend_next_task_tool,
        update_task_status_tool_fn,
    ]


