def calculate_progress(project_id: int, db_path: Optional[str] = None) -> Dict[str, Any]:
    """Calculate project completion progress using Python as source of truth.

    Rule: Equal-weight: Completed tasks / Total tasks * 100.
    Safely returns 0.0% for 0 tasks.
    """
    tasks = get_tasks(project_id, db_path=db_path)
    total = len(tasks)
    if total == 0:
        return {
            "project_id": project_id,
            "total_tasks": 0,
            "completed_tasks": 0,
            "in_progress_tasks": 0,
            "pending_tasks": 0,
            "blocked_tasks": 0,
            "progress_percentage": 0.0,
            "status_breakdown": {
                "Completed": 0,
                "In Progress": 0,
                "Pending": 0,
                "Blocked": 0,
            },
            "method": "Completed tasks / Total tasks * 100 (0 tasks -> 0.0%)",
        }

    status_counts = {"Completed": 0, "In Progress": 0, "Pending": 0, "Blocked": 0}
    for t in tasks:
        s = t.get("status", "Pending")
        status_counts[s] = status_counts.get(s, 0) + 1

    completed = status_counts.get("Completed", 0)
    percentage = round((completed / total) * 100.0, 1)

    return {
        "project_id": project_id,
        "total_tasks": total,
        "completed_tasks": completed,
        "in_progress_tasks": status_counts.get("In Progress", 0),
        "pending_tasks": status_counts.get("Pending", 0),
        "blocked_tasks": status_counts.get("Blocked", 0),
        "progress_percentage": percentage,
        "status_breakdown": status_counts,
        "method": f"Equal-weight: ({completed} completed / {total} total) * 100 = {percentage}%",
    }


def detect_overdue_tasks(
    project_id: int,
    reference_date: Optional[Union[str, date]] = None,
    db_path: Optional[str] = None,
) -> List[Dict[str, Any]]:
    """Detect tasks past due whose status is NOT Completed.

    Calculates days overdue using Python datetime.
    """
    if reference_date is None:
        today = date.today()
    elif isinstance(reference_date, str):
        today = datetime.strptime(reference_date.strip(), "%Y-%m-%d").date()
    else:
        today = reference_date

    tasks = get_tasks(project_id, db_path=db_path)
    overdue_tasks = []

    for t in tasks:
        if t.get("status") == "Completed":
            continue
        due_str = t.get("due_date", "")
        if not due_str:
            continue
        try:
            t_due = datetime.strptime(due_str.strip(), "%Y-%m-%d").date()
            if t_due < today:
                days_over = (today - t_due).days
                overdue_tasks.append({
                    "id": t["id"],
                    "title": t["title"],
                    "milestone_title": t.get("milestone_title", "Unassigned"),
                    "due_date": due_str,
                    "status": t["status"],
                    "priority": t.get("priority", "Medium"),
                    "days_overdue": days_over,
                    "message": f"Overdue by {days_over} day(s) (due {due_str})",
                })
        except ValueError:
            continue

    # Sort most overdue first
    overdue_tasks.sort(key=lambda x: x["days_overdue"], reverse=True)
    return overdue_tasks


def recommend_next_task(
    project_id: int,
    reference_date: Optional[Union[str, date]] = None,
    db_path: Optional[str] = None,
) -> Optional[Dict[str, Any]]:
    """Recommend next eligible task respecting priorities, deadlines, and dependencies.

    Rules:
    - Task must NOT be Completed.
    - Task must NOT be explicitly Blocked.
    - ALL tasks that this task depends on must have status == 'Completed'.
    - Ranking:
      1. Status: 'In Progress' tasks prioritized (finish active work).
      2. Priority weight: Critical (4) > High (3) > Medium (2) > Low (1).
      3. Deadline: Closest due date.
      4. Tie breaker: Lowest task ID.
    """
    if reference_date is None:
        today = date.today()
    elif isinstance(reference_date, str):
        today = datetime.strptime(reference_date.strip(), "%Y-%m-%d").date()
    else:
        today = reference_date

    tasks = get_tasks(project_id, db_path=db_path)
    if not tasks:
        return None

    # Map task id to completion status
    task_map = {t["id"]: t for t in tasks}

    priority_weights = {
        "critical": 4,
        "high": 3,
        "medium": 2,
        "low": 1,
    }

    eligible_tasks = []
    blocked_by_dependency = []

    for t in tasks:
        # Exclude completed and blocked
        if t.get("status") in ("Completed", "Blocked"):
            continue

        # Check dependencies
        deps = t.get("dependencies", [])
        unmet_deps = []
        for dep_id in deps:
            parent_task = task_map.get(dep_id)
            if parent_task and parent_task.get("status") != "Completed":
                unmet_deps.append(f"#{dep_id} '{parent_task['title']}' ({parent_task.get('status')})")

        if unmet_deps:
            blocked_by_dependency.append({
                "task": t,
                "unmet_deps": unmet_deps,
            })
            continue

        # Parse due date for sorting
        try:
            t_due = datetime.strptime(t.get("due_date", "9999-12-31"), "%Y-%m-%d").date()
        except Exception:
            t_due = date.max

        prio_weight = priority_weights.get(t.get("priority", "medium").lower(), 2)
        is_in_progress = 1 if t.get("status") == "In Progress" else 0

        eligible_tasks.append({
            "task": t,
            "is_in_progress": is_in_progress,
            "prio_weight": prio_weight,
            "due_date_obj": t_due,
        })

    if not eligible_tasks:
        if blocked_by_dependency:
            reasons = [f"Task #{b['task']['id']} blocked by: {', '.join(b['unmet_deps'])}" for b in blocked_by_dependency]
            return {
                "task": None,
                "reason": "All remaining incomplete tasks are blocked by pending dependencies.",
                "details": reasons,
            }
        return None

    # Sort eligible:
    # 1) is_in_progress desc
    # 2) prio_weight desc
    # 3) due_date_obj asc
    # 4) task id asc
    eligible_tasks.sort(
        key=lambda item: (
            -item["is_in_progress"],
            -item["prio_weight"],
            item["due_date_obj"],
            item["task"]["id"],
        )
    )

    top = eligible_tasks[0]
    t = top["task"]
    prio_str = t.get("priority", "Medium")
    status_str = t.get("status", "Pending")
    due_str = t.get("due_date", "")

    rationale_parts = []
    if status_str == "In Progress":
        rationale_parts.append("Already in progress")
    rationale_parts.append(f"{prio_str} priority")
    rationale_parts.append(f"Due {due_str}")
    rationale_parts.append("All dependencies satisfied")

    return {
        "task": t,
        "reason": " | ".join(rationale_parts),
        "total_eligible_tasks": len(eligible_tasks),
        "details": {
            "priority": prio_str,
            "status": status_str,
            "due_date": due_str,
            "milestone": t.get("milestone_title", "Unassigned"),
        },
    }


