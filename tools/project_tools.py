def validate_project_input(
    title: str,
    description: str,
    start_date: str,
    deadline: str,
) -> Dict[str, Any]:
    """Validate project basic metadata, dates, and order.

    Returns dict with 'valid' (bool), 'errors' (list of str), and 'warnings' (list of str).
    """
    errors: List[str] = []
    warnings: List[str] = []

    if not title or not title.strip():
        errors.append("Project title is required and cannot be empty.")

    if not start_date or not start_date.strip():
        errors.append("Start date is required.")
    if not deadline or not deadline.strip():
        errors.append("Deadline is required.")

    valid_start = None
    valid_end = None

    if start_date:
        try:
            valid_start = datetime.strptime(start_date.strip(), "%Y-%m-%d").date()
        except ValueError:
            errors.append(f"Invalid start date format '{start_date}'. Expected YYYY-MM-DD.")

    if deadline:
        try:
            valid_end = datetime.strptime(deadline.strip(), "%Y-%m-%d").date()
        except ValueError:
            errors.append(f"Invalid deadline format '{deadline}'. Expected YYYY-MM-DD.")

    if valid_start and valid_end:
        if valid_end < valid_start:
            errors.append(f"Deadline ({valid_end}) cannot be earlier than start date ({valid_start}).")
        elif valid_end == valid_start:
            warnings.append("Project start date and deadline are on the same day.")

    return {
        "valid": len(errors) == 0,
        "errors": errors,
        "warnings": warnings,
    }


def parse_requirements(file_content: Union[bytes, str], filename: str) -> str:
    """Extract plain text from requirement document (.txt, .md, .pdf)."""
    clean_name = filename.lower().strip()
    if clean_name.endswith(".txt") or clean_name.endswith(".md"):
        if isinstance(file_content, bytes):
            return file_content.decode("utf-8", errors="replace").strip()
        return str(file_content).strip()

    if clean_name.endswith(".pdf"):
        if not HAS_PYPDF:
            return "[Error: pypdf library is not installed to read PDF files]"
        try:
            import io
            if isinstance(file_content, str):
                # Assume file path
                reader = pypdf.PdfReader(file_content)
            else:
                reader = pypdf.PdfReader(io.BytesIO(file_content))
            extracted_pages = []
            for i, page in enumerate(reader.pages):
                text = page.extract_text() or ""
                if text.strip():
                    extracted_pages.append(f"--- Page {i + 1} ---\n{text.strip()}")
            return "\n\n".join(extracted_pages).strip() or "[Notice: PDF had no extractable text]"
        except Exception as ex:
            return f"[Error parsing PDF: {str(ex)}]"

    return f"[Error: Unsupported document format '{filename}'. Allowed: .txt, .md, .pdf]"


